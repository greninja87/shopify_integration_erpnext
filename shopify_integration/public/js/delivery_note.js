// delivery_note.js — Shopify status on the Delivery Note form.
//
// Both the Sales Invoice banner and the fulfillment banner want the form's
// single headline slot.  They are fetched together and rendered ONCE, because
// two independent callbacks each calling clear_headline() then
// set_headline_alert() means whichever resolves last silently erases the other's
// message — and which one that is varies per page load.

frappe.ui.form.on('Delivery Note', {
    refresh: function(frm) {
        const si = frappe.xcall(
            'shopify_integration.utils.sales_invoice.get_dn_shopify_invoice_status',
            { dn_name: frm.doc.name }
        ).catch(() => null);

        // Return DNs are Credit Note territory, never fulfillments.
        const ful = frm.doc.is_return
            ? Promise.resolve(null)
            : frappe.xcall(
                'shopify_integration.utils.fulfillment.get_dn_fulfillment_status',
                { dn_name: frm.doc.name }
            ).catch(() => null);

        Promise.all([si, ful]).then(function(results) {
            const si_info = results[0];
            const ful_info = results[1];

            const messages = [];

            const si_msg = shopify_si_message(frm, si_info);
            if (si_msg) messages.push({ text: si_msg, colour: 'yellow' });

            if (ful_info && ful_info.is_shopify) {
                shopify_fulfillment_indicator(frm, ful_info);
                shopify_fulfillment_button(frm, ful_info);

                if (ful_info.error) {
                    messages.push({
                        text: '<b>' + __('Shopify Fulfillment') + ':</b> '
                              + frappe.utils.escape_html(ful_info.error),
                        colour: ful_info.status === 'Failed' ? 'red' : 'orange',
                    });
                }
            }

            if (!messages.length) return;

            // One clear, one set. Worst colour wins so a failure is never
            // downgraded to a merely informational tint.
            const rank = { yellow: 1, orange: 2, red: 3 };
            const colour = messages.reduce(
                (worst, m) => (rank[m.colour] > rank[worst] ? m.colour : worst),
                messages[0].colour
            );

            frm.dashboard.clear_headline();
            frm.dashboard.set_headline_alert(
                '<div style="padding-right:40px;display:block;line-height:1.5;">'
                + messages.map(m => m.text).join('<br>')
                + '</div>',
                colour
            );
        });
    }
});


// ── Sales Invoice ─────────────────────────────────────────────────────────────

function shopify_si_message(frm, info) {
    if (!info || !info.is_shopify || info.has_si) return '';

    if (frm.doc.docstatus !== 1) {
        // Draft DN — say what will happen on submit
        if (info.si_timing === 'Immediate') {
            return __('<b>Shopify Order:</b> The Sales Invoice will be created automatically when this Delivery Note is submitted.');
        }
        if (info.delay_hours > 0) {
            return __('<b>Shopify Order:</b> The Sales Invoice will be auto-generated {0} hour(s) after submission by the Shopify scheduler.', [info.delay_hours]);
        }
        return __('<b>Shopify Order:</b> The Sales Invoice will be auto-generated by the Shopify scheduler after submission.');
    }

    // Submitted DN, SI not yet created — pending or failed
    if (info.si_timing === 'Immediate') {
        return __('<b>Shopify Order:</b> Sales Invoice auto-creation may be pending or has failed.');
    }
    if (info.delay_hours > 0) {
        return __('<b>Shopify Order:</b> Sales Invoice will be auto-generated {0} hour(s) after submission.', [info.delay_hours]);
    }
    return __('<b>Shopify Order:</b> Sales Invoice auto-creation is pending (next scheduler run).');
}


// ── Fulfillment ───────────────────────────────────────────────────────────────

function shopify_fulfillment_indicator(frm, info) {
    if (!info.migrated) {
        frm.dashboard.add_indicator(__('Shopify Fulfillment: not migrated'), 'red');
        return;
    }

    const colours = {
        'Fulfilled': 'green',
        'Partially Fulfilled': 'orange',
        'Pending': 'blue',
        'Failed': 'red',
        'Cancelled': 'grey',
        'Not Applicable': 'grey'
    };

    if (info.status) {
        frm.dashboard.add_indicator(
            __('Shopify: {0}', [__(info.status)]),
            colours[info.status] || 'grey'
        );
        return;
    }

    if (info.enabled && frm.doc.docstatus === 1) {
        // Submitted, enabled, nothing sent yet — say why, so a store on
        // Scheduled doesn't look broken while it waits out the delay.
        let waiting;
        if (info.timing === 'Immediate') {
            waiting = __('Shopify: fulfillment queued');
        } else if (info.timing === 'Scheduled' && info.delay_hours > 0) {
            waiting = __('Shopify: fulfils {0}h after submission', [info.delay_hours]);
        } else if (info.timing === 'Scheduled') {
            waiting = __('Shopify: fulfils at the next hourly run');
        } else {
            waiting = __('Shopify: not fulfilled');
        }
        frm.dashboard.add_indicator(waiting, 'orange');
    }
}


function shopify_fulfillment_button(frm, info) {
    if (!info.migrated || !info.enabled) return;
    // Already fulfilled, or resolved without an ERPNext fulfillment — the
    // server refuses either way, so don't offer a button that cannot work.
    if (info.fulfillment_id || !info.can_fulfil) return;

    const label = (info.status === 'Failed')
        ? __('Retry Shopify Fulfillment')
        : __('Fulfil in Shopify');

    frm.add_custom_button(label, function() {
        shopify_confirm_and_fulfil(frm, info);
    }, __('Shopify'));

    // A store on Manual has no automation behind it, so surface the button as
    // the primary action rather than burying it in a group.
    if (info.timing === 'Manual') {
        frm.page.set_inner_btn_group_as_primary(__('Shopify'));
    }
}


function shopify_confirm_and_fulfil(frm, info) {
    // notifyCustomer reaches a real customer. Say so before it happens.
    const warning = info.notify_customer
        ? '<p>' + __('Shopify will email the customer a shipping confirmation.') + '</p>'
        : '<p>' + __('Customer notification is off — no email will be sent.') + '</p>';

    frappe.confirm(
        '<p>' + __('Mark this order as fulfilled in Shopify?') + '</p>' + warning,
        function() {
            frappe.dom.freeze(__('Fulfilling in Shopify…'));
            frappe.xcall(
                'shopify_integration.utils.fulfillment.fulfil_now',
                { dn_name: frm.doc.name }
            ).then(function(result) {
                frappe.dom.unfreeze();
                if (result && result.ok) {
                    frappe.show_alert({
                        message: __('Fulfilled in Shopify'),
                        indicator: 'green'
                    });
                } else {
                    frappe.msgprint({
                        title: __('Fulfillment Not Sent'),
                        message: frappe.utils.escape_html(
                            (result && result.message) || __('Unknown error')
                        ),
                        indicator: 'red'
                    });
                }
                frm.reload_doc();
            }).catch(function() {
                frappe.dom.unfreeze();
            });
        }
    );
}
